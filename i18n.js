  // State
  let currentLang = 'en';
  let listeners = [];

  function getBrowserLang() {
    const lang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    const short = lang.split('-')[0];
    if (translations[short]) return short;
    return 'en';
  }

  async function detectLang() {
    // 1. Check saved preference
    const saved = localStorage.getItem('fontora-lang');
    if (saved && translations[saved]) return saved;

    // 2. Try geolocation (try multiple free services)
    const geoServices = [
      'https://ipapi.co/json/',
      'https://ipapi.com/json/?key=free',
      'https://api.country.is/'
    ];
    for (const serviceUrl of geoServices) {
      try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 4000);
        const resp = await fetch(serviceUrl, { signal: controller.signal });
        clearTimeout(timeoutId);
        if (resp.ok) {
          const data = await resp.json();
          const cc = (data.country_code || data.country || '').toUpperCase();
          if (cc && countryToLang[cc] && translations[countryToLang[cc]]) {
            return countryToLang[cc];
          }
        }
      } catch (e) {
        // Try next service
      }
    }

    // 3. Fallback to browser language
    return getBrowserLang();
  }

  function t(key) {
    const tr = translations[currentLang] || translations.en;
    return tr[key] || translations.en[key] || key;
  }

  function applyTranslations() {
    const tr = translations[currentLang] || translations.en;
    document.documentElement.lang = currentLang;
    document.documentElement.dir = tr.dir || 'ltr';

    // Apply by data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (tr[key]) el.textContent = tr[key];
    });
    // Apply placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      if (tr[key]) el.placeholder = tr[key];
    });
    // Update default demo text in customize bar
    const demoTextInput = document.getElementById('demoText');
    if (demoTextInput && !demoTextInput.dataset.userTyped) {
      demoTextInput.value = tr.defaultDemo || tr.defaultDemo;
    }

    // Notify listeners
    listeners.forEach(fn => fn(currentLang, tr));
  }

  function setLang(lang) {
    if (!translations[lang]) lang = 'en';
    currentLang = lang;
    localStorage.setItem('fontora-lang', lang);
    applyTranslations();
    // Update language button label
    const langBtn = document.getElementById('langSwitcherBtn');
    if (langBtn) {
      const tr = translations[lang];
      langBtn.innerHTML = `${tr.flag} ${tr.native} <span style="font-size:10px;opacity:.7">▼</span>`;
    }
  }

